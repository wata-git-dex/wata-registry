function interpolateSpanish(text) {
  const rules = [
    [/^Updated (.+) · Read-only$/u, "Actualizado: $1 · Solo lectura"],
    [/^Updated (.+)$/u, "Actualizado: $1"],
    [/^Operational visibility across (.+)\.$/u, "Visibilidad operativa en $1."],
    [/^(.+) filter registry\.$/u, "Registro de filtros de $1."],
    [/^(\d[\d,.]*) distributions · (\d[\d,.]*) follow-ups$/u, "$1 distribuciones · $2 seguimientos"],
    [/^(\d[\d,.]*) recorded families$/u, "$1 familias registradas"],
    [/^(\d[\d,.]*) ready$/u, "$1 disponibles"],
    [/^(\d[\d,.]*) Asset Registry records in (.+)$/u, "$1 registros del Registro de Activos en $2"],
    [/^(\d[\d,.]*) mapped filters in (.+)$/u, "$1 filtros mapeados en $2"],
    [/^(\d[\d,.]*) filters at this location$/u, "$1 filtros en esta ubicación"],
    [/^(\d[\d,.]*) days overdue$/u, "$1 días de retraso"],
    [/^Due in (\d[\d,.]*) days$/u, "Vence en $1 días"],
    [/^(\d[\d,.]*) filter records with follow-up information\.$/u, "$1 registros de filtros con información de seguimiento."],
    [/^(\d[\d,.]*) filters across a shared operational timeline\.$/u, "$1 filtros en una cronología operativa compartida."],
    [/^(\d[\d,.]*) portal-visible issues · operational IDs only$/u, "$1 incidencias visibles en el portal · solo ID operativos"],
    [/^(.+) · Authorized operating view$/u, "$1 · Vista operativa autorizada"],
    [/^(.+) · Portal guide$/u, "$1 · Guía del portal"],
    [/^(.+) · Read-only$/u, "$1 · Solo lectura"],
    [/^Show (.+)$/u, "Mostrar $1"],
    [/^(.+) logo$/u, "Logo de $1"]
  ];
  for (const [pattern, replacement] of rules) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}

export function normalizeLanguage(value) {
  const code = String(value || "").trim().toLowerCase().split("-")[0];
  return SUPPORTED_LANGUAGES.includes(code) ? code : "en";
}

export function translateText(value, language = "en") {
  const text = String(value ?? "");
  if (normalizeLanguage(language) !== "es" || !text) return text;
  return ES[text] || interpolateSpanish(text);
}

export function formatDate(value, language = "en") {
  if (!value) return "—";
  const parsed = new Date(`${value}`.length === 10 ? `${value}T12:00:00Z` : value);
  if (Number.isNaN(parsed.valueOf())) return String(value);
  return parsed.toLocaleDateString(normalizeLanguage(language) === "es" ? "es-419" : "en-US", {
    year: "numeric", month: "short", day: "numeric", timeZone: "UTC"
  });
}

export function formatNumber(value, language = "en") {
  return Number(value || 0).toLocaleString(normalizeLanguage(language) === "es" ? "es-419" : "en-US");
}
